//! Режим раннера: приложение берёт задачи с сервера и ведёт их обычными карточками своей очереди.
//!
//! Поток раннера (`runner::Runner`) только создаёт карточку в базе, пересылает в свой `Tee` события, которые присылает
//! поток очереди, и ждёт итога по каналу. Запись в игре идёт в единственном потоке очереди приложения, поэтому «не больше
//! одной записи за раз» обеспечивается самой очередью, а не новым замком. Токен живёт в `runner::Token` и не попадает
//! ни в настройки, ни в журналы.
#![allow(dead_code)] // хаб подключается к окну и настройкам следующими планами фазы 8

pub mod hub;

#[allow(unused_imports)]
pub use hub::{ExecFactory, RemoteExecutor, RemoteHub, queue_runner};

#[cfg(test)]
pub(crate) mod testkit;
#[cfg(test)]
mod tests;

/// Ссылка карточки на выдачу задачи сервера: пара «номер задачи, эпоха» даёт ровно одну карточку.
pub fn external_ref(job_id: i64, epoch: i64) -> String {
    format!("srv:{job_id}:{epoch}")
}

/// Подпись новой карточки: строится только из номера задачи, текст от друга в неё не попадает.
pub fn card_label(job_id: i64) -> String {
    format!("Задача с сервера #{job_id}")
}
